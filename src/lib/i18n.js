// Messages techniques renvoyés par le serveur d'authentification ou la base (en anglais à l'origine).
// Renvoie la version traduite, ou null si le message n'est pas reconnu (on garde alors l'original).
export function traduireErreurServeur(msg, lang) {
  if (!msg || typeof msg !== "string") return null;
  const l = lang || langCourante();
  const m = msg.toLowerCase();
  const rules = [
    ["invalid login credentials", "err_srv_credentials"],
    ["email not confirmed", "err_srv_email_non_confirme"],
    ["user already registered", "err_srv_utilisateur_existe"],
    ["already been registered", "err_srv_utilisateur_existe"],
    ["password should be at least", "err_srv_mdp_court"],
    ["should be different from the old password", "err_srv_mdp_identique"],
    ["rate limit", "err_srv_limite"],
    ["for security purposes, you can only request this", "err_srv_limite"],
    ["too many requests", "err_srv_limite"],
    ["token has expired or is invalid", "err_srv_token"],
    ["otp_expired", "err_srv_token"],
    ["invalid totp code", "err_code_incorrect"],
    ["row-level security", "err_srv_rls"],
    ["duplicate key value", "err_srv_doublon"],
    ["failed to fetch", "err_reseau"],
    ["networkerror", "err_reseau"],
    ["load failed", "err_reseau"],
    ["network request failed", "err_reseau"],
  ];
  for (const [needle, key] of rules) if (m.includes(needle)) return t(l, key);
  return null;
}

// Texte d'erreur à afficher à l'utilisateur : version traduite si disponible, sinon message brut.
export function libelleErreur(err) {
  if (!err) return "";
  return err.messageLocalise || err.message || String(err);
}
